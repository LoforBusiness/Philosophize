// ─────────────────────────────────────────────────────────────────────────────
// WHERE EACH HELD POSE'S HANDS REST, so a dialogue figure's arms can hold still
// (LESSON_RULES AP18).
//
// The owner, 2026-10-01: *"when there's nothing being said, I do not want their arms
// to be moving. Usually they're moving in a really AI looking way where they're slowly
// moving back and forth … a stickman's arms will only move in ways that make sense in
// the scene."* Every living hold in moves.ts (and stand() under all of them) swings its
// hands on a slow sine, which is that exact look.
//
// So each hold's hands are given ONE place: the average of where its loop takes them,
// sampled over two minutes of its own clock. A figure in a still pose keeps the shape
// the pose was drawn to have, with its hands where they spend their time, and nothing
// in the arms moves unless the scene moves them (a reach, a carry, a played action).
//
// Writes the table between the ARM_REST markers in moves.ts. Run it again after any
// held pose changes; `check:dialogue` re-derives the table and fails a stale one.
//   node scripts/make-arm-rest.mjs [--check]
// ─────────────────────────────────────────────────────────────────────────────
import fs from 'node:fs';
import path from 'node:path';
import { loadRig } from './lib/loadrig.mjs';

const FILE = path.resolve('components/lesson/cinematic/moves.ts');
const BEGIN = '// ARM_REST:BEGIN';
const END = '// ARM_REST:END';
const ACTS = 200;
const POSTURES = 40;

export async function armRestTable() {
  const { MOVES } = await loadRig();
  const mean = (f) => {
    let lx = 0, ly = 0, rx = 0, ry = 0, n = 0;
    for (let t = 0; t < 120; t += 0.05) {
      const s = f(t);
      lx += s.fistL.x; ly += s.fistL.y; rx += s.fistR.x; ry += s.fistR.y; n += 1;
    }
    return [lx, ly, rx, ry].map((v) => Math.round((v / n) * 10) / 10);
  };
  const acts = [];
  for (let a = 1; a <= ACTS; a += 1) {
    let ok = true;
    try { MOVES.actStance(a, 0, 1); } catch { ok = false; }
    acts.push(ok ? mean((t) => MOVES.actStance(a, t, 1)) : null);
  }
  const postures = [];
  for (let p = 0; p < POSTURES; p += 1) postures.push(mean((t) => MOVES.postureHold(p, t)));
  return { acts, postures };
}

function render({ acts, postures }) {
  const row = (v) => (v ? `[${v.join(', ')}]` : 'null');
  const chunk = (list) => {
    const lines = [];
    for (let i = 0; i < list.length; i += 4) lines.push(`  ${list.slice(i, i + 4).map(row).join(', ')},`);
    return lines.join('\n');
  };
  return [
    BEGIN + ' — generated by scripts/make-arm-rest.mjs; do not edit by hand.',
    '/** Where each act\'s hands rest, [lx, ly, rx, ry], act 1 first: the mean of its loop. */',
    'const ARM_REST_ACT: readonly (readonly number[] | null)[] = [',
    chunk(acts),
    '];',
    '/** The same for each posture, code 0 first. */',
    'const ARM_REST_POSTURE: readonly (readonly number[])[] = [',
    chunk(postures),
    '];',
    END,
  ].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve('scripts/make-arm-rest.mjs')) {
  const text = render(await armRestTable());
  const src = fs.readFileSync(FILE, 'utf8');
  const a = src.indexOf(BEGIN), b = src.indexOf(END);
  if (a < 0 || b < 0) throw new Error('moves.ts has no ARM_REST markers');
  const now = src.slice(a, b + END.length);
  if (process.argv.includes('--check')) {
    console.log(now === text ? 'ARM_REST is current' : 'ARM_REST is STALE: run node scripts/make-arm-rest.mjs');
    process.exit(now === text ? 0 : 1);
  }
  if (now === text) console.log('ARM_REST unchanged');
  else { fs.writeFileSync(FILE, src.slice(0, a) + text + src.slice(b + END.length)); console.log('ARM_REST written'); }
}
