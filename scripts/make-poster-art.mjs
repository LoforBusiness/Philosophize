// Draw the Home shelf's subject posters to PNG.
//
//   node scripts/make-poster-art.mjs          (npm run make:posters)
//
// components/subjects/posters.ts builds each poster as an SVG string for its box, and
// everywhere else in the app it is painted live by react-native-svg. The Home shelf is
// the one place a poster is SWIPED THROUGH, and live SVG there cost a hitch on every
// swipe (2026-09-30): SvgXml parses the string on the JS thread when its card mounts
// and turns every path into a native view, so a shelf that mounted cards as they came
// into view built a whole drawing in the middle of the reader's gesture. A PNG is
// decoded once and drawn like any photograph — the Quick Start pictures' reason (§19).
//
// Every card on the shelf has the same shape — cardArtHeight is a fixed share of the
// card's width — so one picture per subject serves every phone, laid with `cover`
// (the aspect moves by under 0.1% between a 320dp and a 430dp phone). It is drawn at
// the card box a 390dp phone uses, SCALE times over, which is sharp on the widest phone.
//
// It writes components/subjects/posterArt.ts, the table the card reads, with a STAMP
// per picture: a hash of the SVG it was drawn from. `check:subjects` re-derives every
// stamp, so a poster edited in posters.ts and not redrawn here fails the build rather
// than shipping an old picture on Home and a new one on Learn.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';
import JimpPkg from 'jimp-compact';

const Jimp = JimpPkg.default || JimpPkg;
const REPO = process.cwd();
const SCALE = Number(process.env.SCALE || 3.4);
const { transform } = await import(pathToFileURL(path.join(REPO, 'node_modules/sucrase/dist/index.js')).href);

/** A module whose only imports are handed to it (sheet-subjects.mjs's idiom). */
function loadWith(rel, deps = {}) {
  const js = transform(fs.readFileSync(path.join(REPO, rel), 'utf8'), { transforms: ['typescript', 'imports'] }).code;
  const mod = { exports: {} };
  new Function('exports', 'module', 'require', js)(mod.exports, mod, (m) => {
    if (deps[m]) return deps[m];
    throw new Error(`${rel} imports ${m}, which make-poster-art cannot hand it`);
  });
  return mod.exports;
}
const tone = loadWith('components/shared/tone.ts');
const P = loadWith('components/subjects/posters.ts', { '@/components/shared/tone': tone });
const S = loadWith('data/subjects.ts');
const L = loadWith('components/subjects/tileLayout.ts');

/** The poster box on a 390dp phone's card: the card less its 2px border each side. */
const CARD_W = L.cardWidth(390);
const W = CARD_W - 4;
const H = L.cardArtHeight(CARD_W);
const stampOf = (xml) => crypto.createHash('sha1').update(xml).digest('hex').slice(0, 12);

const outDir = path.join(REPO, 'assets/images/posters');
fs.mkdirSync(outDir, { recursive: true });
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'ashmere-posters-'));
const CHROME = process.env.CHROME || 'C:/Program Files/Google/Chrome/Application/chrome.exe';
const PXW = Math.round(W * SCALE);
const PXH = Math.round(H * SCALE);

const rows = [];
for (const s of S.SUBJECTS) {
  const xml = P.posterXml(s.slug, s.hue, W, H);
  const page = path.join(tmp, `${s.slug}.html`);
  const shot = path.join(tmp, `${s.slug}.png`);
  fs.writeFileSync(page, `<!doctype html><style>html,body{margin:0;background:${s.hue}}svg{display:block}</style>${xml}`);
  execFileSync(CHROME, ['--headless=new', '--disable-gpu', '--hide-scrollbars', `--force-device-scale-factor=${SCALE}`,
    `--window-size=${W + 40},${H + 200}`, `--screenshot=${shot}`, pathToFileURL(page).href], { stdio: 'ignore' });
  const im = await Jimp.read(shot);
  if (im.bitmap.width < PXW || im.bitmap.height < PXH) throw new Error(`${s.slug}: screenshot ${im.bitmap.width}x${im.bitmap.height} is smaller than ${PXW}x${PXH}`);
  im.crop(0, 0, PXW, PXH);
  const out = path.join(outDir, `card-${s.slug}.png`);
  await im.writeAsync(out);
  rows.push({ slug: s.slug, stamp: stampOf(xml) });
  console.log(`${path.relative(REPO, out)}   ${PXW}x${PXH}   ${Math.round(fs.statSync(out).size / 1024)}KB`);
}

let table = `// GENERATED by \`npm run make:posters\` from components/subjects/posters.ts.
// Do not edit: change the poster and run it again. check:subjects fails a stale stamp.
import type { ImageSourcePropType } from 'react-native';

/** The box every picture here was drawn for: a 390dp phone's Home card, less its border. */
export const CARD_POSTER_BOX = { w: ${W}, h: ${H} } as const;

/** Each subject's Home-shelf poster, pre-drawn (see scripts/make-poster-art.mjs). */
export const CARD_POSTER: Record<string, { source: ImageSourcePropType; stamp: string }> = {
`;
for (const r of rows) table += `  '${r.slug}': { source: require('@/assets/images/posters/card-${r.slug}.png'), stamp: '${r.stamp}' },\n`;
table += '};\n';
fs.writeFileSync(path.join(REPO, 'components/subjects/posterArt.ts'), table);
console.log(`components/subjects/posterArt.ts   ${rows.length} posters at ${W}x${H}`);
