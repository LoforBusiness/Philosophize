// DRAW A LESSON'S DETAILED ART TO PICTURES (LESSON_RULES AM13).
//
//   node scripts/make-lesson-art.mjs            (npm run make:lesson-art)
//
// Some things on a stage cannot be drawn well from boxes, ellipses and triangles: a
// carved relief of a king in his chariot, a horse in full gallop, a ship's hull. A reader:
// *"the design just looks like a lot of shapes that are meant to look like the objects …
// I don't want just random shapes."* Those are drawn here as SVG — real curves, drawn
// against fetched references — and baked to a PNG the scene shows with one <Image>, the
// way the subject posters are (make-poster-art.mjs). A picture is also cheaper on a phone
// than the dozens of Views the shapes took (AT7).
//
// Each ART entry names a module in scripts/lib/lessonart/ and the function that returns its
// SVG, drawn in SCENE units with its own viewBox, so the picture drops onto the stage at
// that box with no conversion. It writes assets/lesson-art/<name>.png at SCALE pixels a
// unit (transparent where nothing is drawn) and components/lesson/cinematic/lessonArt.ts,
// the table a scene reads, with a STAMP per picture: check:lesson-art re-derives each
// stamp from its SVG, so a drawing edited and not redrawn fails the build.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';
import JimpPkg from 'jimp-compact';
import { ART } from './lib/lessonart/index.mjs';

const Jimp = JimpPkg.default || JimpPkg;
const REPO = process.cwd();
// 6 pixels a stage unit: sharp on a ~3x phone even with the camera pushed in to 1.72x.
// (A run at the old default of 4 once quietly re-baked every picture a third softer.)
const SCALE = Number(process.env.SCALE || 6);
const CHROME = process.env.CHROME || 'C:/Program Files/Google/Chrome/Application/chrome.exe';
const ONLY = process.argv[2] || null;
const outDir = path.join(REPO, 'assets/lesson-art');
fs.mkdirSync(outDir, { recursive: true });
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'ashmere-lessonart-'));
export const stampOf = (svg) => crypto.createHash('sha1').update(svg).digest('hex').slice(0, 12);

const rows = [];
for (const a of ART) {
  // a drawing that returns only its body is wrapped here: its viewBox is `view`, and it is
  // laid at `box` size, stretched to it exactly as the object it replaces was fitted
  const body = a.svg();
  const v = a.view, b = a.box;
  const svg = body.startsWith('<svg') ? body
    : `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${v.x} ${v.y} ${v.w} ${v.h}" width="${b.w}" height="${b.h}" preserveAspectRatio="none">${body}</svg>`;
  const stamp = stampOf(svg);
  rows.push({ ...a, stamp });
  if (ONLY && a.name !== ONLY) continue;
  const pxw = Math.round(b.w * SCALE), pxh = Math.round(b.h * SCALE);
  const page = path.join(tmp, `${a.name}.html`);
  const shot = path.join(tmp, `${a.name}.png`);
  fs.writeFileSync(page, `<!doctype html><style>html,body{margin:0;background:transparent}svg{display:block}</style>${svg}`);
  execFileSync(CHROME, ['--headless=new', '--disable-gpu', '--hide-scrollbars', '--default-background-color=00000000',
    `--force-device-scale-factor=${SCALE}`, `--window-size=${Math.ceil(b.w) + 40},${Math.ceil(b.h) + 200}`,
    `--screenshot=${shot}`, pathToFileURL(page).href], { stdio: 'ignore' });
  const im = await Jimp.read(shot);
  im.crop(0, 0, pxw, pxh);
  const out = path.join(outDir, `${a.name}.png`);
  await im.writeAsync(out);
  console.log(`${path.relative(REPO, out)}   ${pxw}x${pxh}   ${Math.round(fs.statSync(out).size / 1024)}KB`);
}

let table = `// GENERATED by \`npm run make:lesson-art\` from scripts/lib/lessonart/. Do not edit:
// change the drawing and run it again. check:lesson-art fails a stale stamp.
import type { ImageSourcePropType } from 'react-native';

/** A lesson's detailed art, pre-drawn: where it sits on the stage (scene units) and its picture. */
export const LESSON_ART: Record<string, { source: ImageSourcePropType; x: number; y: number; w: number; h: number; stamp: string }> = {
`;
for (const r of rows) {
  // a picture not yet drawn stays out of the table, so a require() of a missing PNG can
  // never break the bundle while somebody else is still drawing (check:lesson-art fails it)
  if (!fs.existsSync(path.join(outDir, `${r.name}.png`))) { console.log(`  (${r.name}: no PNG yet — left out of the table)`); continue; }
  table +=`  '${r.name}': { source: require('@/assets/lesson-art/${r.name}.png'), x: ${r.box.x}, y: ${r.box.y}, w: ${r.box.w}, h: ${r.box.h}, stamp: '${r.stamp}' },\n`;
}
table += '};\n';
fs.writeFileSync(path.join(REPO, 'components/lesson/cinematic/lessonArt.ts'), table);
console.log(`components/lesson/cinematic/lessonArt.ts   ${rows.length} pictures`);
