// Draw the profile pictures.
//
//   node scripts/make-profile-art.mjs          (npm run make:profile-art)
//
// components/shared/profileScenes.ts holds every place as SVG — zero imports, so it
// loads here in plain Node — and this draws each one in headless Chrome to
// assets/images/profile/<id>.png, then writes components/shared/profileSceneArt.ts,
// the table data/profileBackgrounds.ts reads: the file, and the sky and ground
// colours a box paints above and below the picture.
//
// PNGs rather than SVG in the app, for §19's reason: react-native-svg paints every
// <Svg> into a bitmap the size of its box, held for as long as its tab is built, and
// Profile and Home are always built. An <Image> is decoded once.
//
// SCALE 1.4 makes the canvas 1680px wide: the Profile header draws it about 420dp
// wide, which is 1260px at 3× density, so this stays sharp with room to spare.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';
import JimpPkg from 'jimp-compact';

const Jimp = JimpPkg.default || JimpPkg;
const REPO = process.cwd();
const SCALE = Number(process.env.SCALE || 1.4);
const { transform } = await import(pathToFileURL(path.join(REPO, 'node_modules/sucrase/dist/index.js')).href);
const SRC = path.join(REPO, 'components/shared/profileScenes.ts');
const GEO = path.join(REPO, 'components/shared/profileSceneGeometry.ts');
const src = fs.readFileSync(SRC, 'utf8');
const geoSrc = fs.readFileSync(GEO, 'utf8');
const load = (code, req) => {
  const m = { exports: {} };
  new Function('exports', 'module', 'require', transform(code, { transforms: ['typescript', 'imports'] }).code)(m.exports, m, req);
  return m.exports;
};
const geo = load(geoSrc, (m) => { throw new Error(`profileSceneGeometry.ts imports ${m}`); });
const mod = { exports: load(src, (m) => { if (m === './profileSceneGeometry') return geo; throw new Error(`profileScenes.ts imports ${m}`); }) };
const { PROFILE_SCENES, READING_ROOM, PS_W, PS_H } = mod.exports;

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'ashmere-profile-'));
const CHROME = process.env.CHROME || 'C:/Program Files/Google/Chrome/Application/chrome.exe';
const PW = Math.round(PS_W * SCALE);
const PH = Math.round(PS_H * SCALE);

// The Pass tab's reading room is drawn with the same kit, to its own folder.
const ALL = [...PROFILE_SCENES.map((sc) => ({ sc, dir: 'profile' })), { sc: READING_ROOM, dir: 'pass' }];
for (const { sc, dir } of ALL) {
  const page = path.join(tmp, `${sc.id}.html`);
  const shot = path.join(tmp, `${sc.id}.png`);
  fs.writeFileSync(page, `<!doctype html><style>html,body{margin:0;background:${sc.ground}}svg{display:block}</style>`
    + `<svg xmlns="http://www.w3.org/2000/svg" width="${PS_W}" height="${PS_H}" viewBox="0 0 ${PS_W} ${PS_H}">${sc.svg}</svg>`);
  execFileSync(CHROME, ['--headless=new', '--disable-gpu', '--hide-scrollbars', `--force-device-scale-factor=${SCALE}`,
    `--window-size=${PS_W + 40},${PS_H + 200}`, `--screenshot=${shot}`, pathToFileURL(page).href], { stdio: 'ignore' });
  const im = await Jimp.read(shot);
  if (im.bitmap.width < PW || im.bitmap.height < PH) throw new Error(`${sc.id}: screenshot ${im.bitmap.width}x${im.bitmap.height} is smaller than ${PW}x${PH}`);
  im.crop(0, 0, PW, PH);
  fs.mkdirSync(path.join(REPO, 'assets/images', dir), { recursive: true });
  const out = path.join(REPO, 'assets/images', dir, `${sc.id}.png`);
  await im.writeAsync(out);
  console.log(`${path.relative(REPO, out)}   ${PW}x${PH}   ${Math.round(fs.statSync(out).size / 1024)}KB`);
}

// The stamp lets a check say "the scenes were edited and not redrawn".
const stamp = crypto.createHash('sha1').update(src + geoSrc).digest('hex').slice(0, 12);
let table = `// GENERATED by \`npm run make:profile-art\` from components/shared/profileScenes.ts.\n`
  + `// Do not edit: change the scene and run it again.\n`
  + `import type { ImageSourcePropType } from 'react-native';\n\n`
  + `export const PROFILE_ART_STAMP = '${stamp}';\n\n`
  + `export interface ProfileSceneArt { name: string; source: ImageSourcePropType; sky: string; ground: string; focus: { x: number; y: number } }\n\n`
  + `export const PROFILE_SCENE_ART: Record<string, ProfileSceneArt> = {\n`;
for (const sc of PROFILE_SCENES) {
  table += `  '${sc.id}': { name: '${sc.name}', source: require('@/assets/images/profile/${sc.id}.png'), sky: '${sc.sky}', ground: '${sc.ground}', focus: { x: ${sc.focus.x}, y: ${sc.focus.y} } },\n`;
}
table += `};\n\n/** The Pass tab's reading room. */\n`
  + `export const READING_ROOM_ART = { source: require('@/assets/images/pass/reading-room.png') as ImageSourcePropType, sky: '${READING_ROOM.sky}', ground: '${READING_ROOM.ground}' };\n`;
fs.writeFileSync(path.join(REPO, 'components/shared/profileSceneArt.ts'), table);
console.log(`wrote components/shared/profileSceneArt.ts  (${PROFILE_SCENES.length} places, stamp ${stamp})`);
