// make:road-art — bake each subject road's scenery layers (components/branch/sceneArt.ts)
// into PNGs the road draws instead of SVG.
//
//   npm run make:road-art
//
// WHY. BranchWorld drew every scenery layer as a 1,000-unit-wide <Svg>, twice (two tiles
// for the endless scroll). react-native-svg paints each <Svg> into a bitmap the size of
// its box, in software, on the UI thread: 24–40 MB of path fills a road, all at the
// moment the road's world was built. That is why the road appeared late, after the top
// of the screen (2026-10-03). A PNG is decoded off the UI thread, and the two tiles of a
// layer draw ONE decoded bitmap, so the same scenery costs a third of the memory and
// none of the drawing.
//
// Drawn in plain Node with the repo's own rasteriser (scripts/lib/rasterpath.mjs), the
// one sheet-scene composites the road with, at SCALE pixels per world unit: the shaded
// face first, then the mass, each anti-aliased, over transparency. Writes
// assets/images/road/<place>-<unit>-<layer>.png and components/branch/roadArt.ts, with
// a stamp per place that `check:plates` re-derives.
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { coverage, rgb } from './lib/rasterpath.mjs';

const REPO = process.cwd();
const S = await import(pathToFileURL(path.join(REPO, 'components/branch/sceneArt.ts')).href);
const { default: Jimp } = await import(pathToFileURL(path.join(REPO, 'node_modules/jimp-compact/dist/jimp.js')).href);
const OUT = path.join(REPO, 'assets/images/road');
const ART = path.join(REPO, 'components/branch/roadArt.ts');
/** Pixels per world unit: a road's scenery is behind the figure and moves; 2 is crisp on a 1080 phone's ~2.6/unit only where it is near, and the near layers are low and short. */
export const SCALE = 2;
/** The seven live roads (AP15). */
export const PLACES = ['philosophy', 'psychology', 'personal-growth', 'business', 'economics', 'science', 'history'];

/**
 * How many units a road has, counted out of data/branches/<place>/paths. EVERY unit is baked:
 * the road changes its scenery at each unit's start (BranchWorld's `vp.s`), and a unit with no
 * picture falls back to live <Svg> layers painted on the UI thread. Only unit 0 used to be baked,
 * so the second unit added on 2026-10-09 brought the opening lag back (2026-10-09).
 */
export function unitsOf(place) {
  const dir = path.join(REPO, 'data/branches', place, 'paths');
  return fs.readdirSync(dir, { withFileTypes: true }).filter((d) => d.isDirectory()).length;
}

export function roadStamp(place, unit) {
  return crypto.createHash('sha1').update(JSON.stringify({ SCALE, layers: S.sceneLayers(place, unit) })).digest('hex').slice(0, 16);
}

async function bake(l, file) {
  const w = Math.round(S.TILE_W * SCALE), h = Math.ceil(l.h * SCALE);
  const img = new Jimp(w, h, 0x00000000);
  const o = img.bitmap.data;
  const paint = (d, hex) => {
    const cov = coverage(d, w, h, 0, -l.top, SCALE, 4);
    const [r, g, b] = rgb(hex);
    for (let i = 0; i < w * h; i++) {
      const a = Math.min(1, cov[i]);
      if (a <= 0.002) continue;
      const j = i * 4;
      const da = o[j + 3] / 255;
      const oa = a + da * (1 - a);
      o[j] = Math.round((r * a + o[j] * da * (1 - a)) / oa);
      o[j + 1] = Math.round((g * a + o[j + 1] * da * (1 - a)) / oa);
      o[j + 2] = Math.round((b * a + o[j + 2] * da * (1 - a)) / oa);
      o[j + 3] = Math.round(oa * 255);
    }
  };
  if (l.under) paint(l.under, l.underTone);
  paint(l.d, l.tone);
  await img.writeAsync(file);
  return { w, h, kb: fs.statSync(file).size / 1024 };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  fs.mkdirSync(OUT, { recursive: true });
  const rows = [];
  for (const place of PLACES) for (let unit = 0; unit < unitsOf(place); unit++) {
    const layers = S.sceneLayers(place, unit);
    const files = [];
    let kb = 0;
    for (let i = 0; i < layers.length; i++) {
      const name = `${place}-${unit}-${i}.png`;
      const r = await bake(layers[i], path.join(OUT, name));
      kb += r.kb;
      files.push(name);
    }
    rows.push({ key: `${place}:${unit}`, files, stamp: roadStamp(place, unit), meta: layers.map((l) => ({ k: l.k, top: l.top, h: l.h })) });
    console.log(`  ${place}:${unit}: ${layers.length} layers, ${kb.toFixed(0)}KB`);
  }
  fs.writeFileSync(ART, `// GENERATED by \`npm run make:road-art\`. Do not edit.
// Each road's scenery layers as baked pictures, in sceneLayers' order (make-road-art.mjs).

export const ROAD_SCALE = ${SCALE};

export const ROAD_STAMP: Record<string, string> = {
${rows.map((r) => `  '${r.key}': '${r.stamp}',`).join('\n')}
};

export const ROAD_ART: Record<string, number[]> = {
${rows.map((r) => `  '${r.key}': [\n${r.files.map((f) => `    require('../../assets/images/road/${f}'),`).join('\n')}\n  ],`).join('\n')}
};

/**
 * What the road needs to lay each baked picture: its parallax, its top and its height. The road
 * reads these instead of calling sceneLayers, which builds every path of the scenery in
 * JS — work a baked road throws away, on the frame the screen arrives (2026-10-03).
 */
export const ROAD_LAYERS: Record<string, { k: number; top: number; h: number }[]> = {
${rows.map((r) => `  '${r.key}': [${r.meta.map((m) => `{ k: ${m.k}, top: ${m.top}, h: ${m.h} }`).join(', ')}],`).join('\n')}
};
`);
  console.log(`wrote ${path.relative(REPO, ART)}`);
}
