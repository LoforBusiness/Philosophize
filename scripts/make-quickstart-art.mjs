// Draw the Quick Start pictures.
//
//   node scripts/make-quickstart-art.mjs          (npm run make:quickstart)
//
// components/home/quickStartScenes.ts holds every scene as SVG — zero imports, so it
// loads here in plain Node — and this draws each one in headless Chrome to
// assets/images/quickstart/<id>.png, then writes components/home/quickStartArt.ts,
// the table the card reads: which pictures belong to which subject, with the sky and
// ground colours that fill the card above and below the picture.
//
// PNGs rather than SVG in the app, for §19's reason: react-native-svg paints every
// <Svg> into a bitmap the size of its box, held for as long as its tab is built, and
// Home is a tab that is always built. An <Image> of the same picture is decoded once
// and costs no more than any other photograph.
//
// The scenes are 1080 units square and drawn at SCALE × that: the card shows the
// picture at up to about 1.25 × its width, which is ~530dp on a wide phone, so at 3×
// density a 1080px image would be drawn soft.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';
import JimpPkg from 'jimp-compact';

const Jimp = JimpPkg.default || JimpPkg;
const REPO = process.cwd();
const SCALE = Number(process.env.SCALE || 1.4);
const { transform } = await import(pathToFileURL(path.join(REPO, 'node_modules/sucrase/dist/index.js')).href);
const src = fs.readFileSync(path.join(REPO, 'components/home/quickStartScenes.ts'), 'utf8');
const js = transform(src, { transforms: ['typescript', 'imports'] }).code;
const mod = { exports: {} };
new Function('exports', 'module', 'require', js)(mod.exports, mod, (m) => { throw new Error(`quickStartScenes.ts imports ${m}`); });
const { QS_SCENES, QS_CANVAS } = mod.exports;

const outDir = path.join(REPO, 'assets/images/quickstart');
fs.mkdirSync(outDir, { recursive: true });
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'ashmere-qs-'));
const CHROME = process.env.CHROME || 'C:/Program Files/Google/Chrome/Application/chrome.exe';
const PX = Math.round(QS_CANVAS * SCALE);

for (const sc of QS_SCENES) {
  const page = path.join(tmp, `${sc.id}.html`);
  const shot = path.join(tmp, `${sc.id}.png`);
  fs.writeFileSync(page, `<!doctype html><style>html,body{margin:0;background:${sc.sky}}svg{display:block}</style>`
    + `<svg xmlns="http://www.w3.org/2000/svg" width="${QS_CANVAS}" height="${QS_CANVAS}" viewBox="0 0 ${QS_CANVAS} ${QS_CANVAS}">${sc.svg}</svg>`);
  execFileSync(CHROME, ['--headless=new', '--disable-gpu', '--hide-scrollbars', `--force-device-scale-factor=${SCALE}`,
    `--window-size=${QS_CANVAS + 40},${QS_CANVAS + 200}`, `--screenshot=${shot}`, pathToFileURL(page).href], { stdio: 'ignore' });
  const im = await Jimp.read(shot);
  if (im.bitmap.width < PX || im.bitmap.height < PX) throw new Error(`${sc.id}: screenshot ${im.bitmap.width}x${im.bitmap.height} is smaller than ${PX}`);
  im.crop(0, 0, PX, PX);
  const out = path.join(outDir, `${sc.id}.png`);
  await im.writeAsync(out);
  console.log(`${path.relative(REPO, out)}   ${PX}x${PX}   ${Math.round(fs.statSync(out).size / 1024)}KB`);
}

// The table, grouped by subject in rotation order.
const bySubject = {};
for (const sc of QS_SCENES) (bySubject[sc.subject] ||= []).push(sc);
let table = `// GENERATED by \`npm run make:quickstart\` from components/home/quickStartScenes.ts.
// Do not edit: change the scene and run it again.
import type { ImageSourcePropType } from 'react-native';
import type { QsSubject } from './quickStartScenes';

export interface QsArt {
  id: string;
  source: ImageSourcePropType;
  sky: string;
  ground: string;
}

export const QS_ART: Record<QsSubject, readonly QsArt[]> = {
`;
for (const [subject, list] of Object.entries(bySubject)) {
  table += `  '${subject}': [\n`;
  for (const sc of list) table += `    { id: '${sc.id}', source: require('@/assets/images/quickstart/${sc.id}.png'), sky: '${sc.sky}', ground: '${sc.ground}' },\n`;
  table += '  ],\n';
}
table += '};\n';
fs.writeFileSync(path.join(REPO, 'components/home/quickStartArt.ts'), table);
console.log(`components/home/quickStartArt.ts   ${QS_SCENES.length} pictures in ${Object.keys(bySubject).length} subjects`);
