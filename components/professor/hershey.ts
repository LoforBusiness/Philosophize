// ─────────────────────────────────────────────────────────────────────────────
// SINGLE-STROKE LETTERS FOR THE CHALKBOARD.
//
// Chalk is DRAWN, a stroke at a time, so the board needs letters that are the path a
// hand takes rather than an outline to fill — which is what a font file holds. These
// are Dr A. V. Hershey's single-stroke vector fonts (US National Bureau of Standards,
// 1967, public domain), the "Sans 1-stroke" set, as packaged by hersheytext (MIT,
// (c) 2014 James T). Only the glyphs the professor's board uses are kept.
//
// Units: a capital runs from y 1 to y 22, the baseline is 22, and `w` is the
// advance. Each stroke is a flat list of x, y pairs — one pen-down movement.
// The full stop and comma are this project's own: the set's sit above the baseline.
// So are the dots of ? and !, round where the set draws a four-point diamond.
//
// ZERO IMPORTS, so the chalk layout and its checker run in plain Node.
// GENERATED once from the font data; edit by hand only to add a glyph.
// ─────────────────────────────────────────────────────────────────────────────

export interface Glyph {
  /** Advance, in font units. */
  w: number;
  /** Pen strokes, each a flat list of x, y pairs. */
  s: number[][];
}

